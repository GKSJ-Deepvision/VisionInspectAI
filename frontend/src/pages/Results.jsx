import { useLocation } from "react-router-dom";
import Layout from "../components/Layout";

import {
  Download,
  CheckCircle,
  ShieldCheck,
  ImageIcon,
  Layers,
  AlertTriangle,
} from "lucide-react";

import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";

function Results() {

  const location = useLocation();

  const result = location.state?.result;
  const detections = result?.detections || [];
  const processedImage = location.state?.processedImage;


  const downloadPDF = () => {

    if (!result) return;

    const doc = new jsPDF();

    doc.setFont("helvetica", "bold");

    doc.setFontSize(22);
    doc.text("VisionInspect AI", 105, 20, {
      align: "center",
    });

    doc.setFontSize(15);
    doc.text("Quality Inspection Report", 105, 30, {
      align: "center",
    });

    doc.setFontSize(10);
    doc.setFont("helvetica", "normal");

    doc.text(
      `Generated: ${new Date().toLocaleString()}`,
      105,
      38,
      { align: "center" }
    );

    let y = 48;

    // Original Image
    if (location.state?.originalImage) {
      doc.setFontSize(12);
      doc.setFont("helvetica", "bold");
      doc.text("Original Image", 50, y, {
        align: "center",
      });

      doc.addImage(
        location.state.originalImage,
        "PNG",
        20,
        y + 5,
        60,
        60
      );
      doc.rect(20, y + 5, 60, 60);
    }

    // Processed Image
    if (processedImage) {
      doc.setFontSize(12);
      doc.text("Processed Image", 150, y, {
        align: "center",
      });

      doc.addImage(
        processedImage,
        "PNG",
        120,
        y + 5,
        60,
        60
      );
      doc.rect(120, y + 5, 60, 60);
    }

    y += 72;

    autoTable(doc, {
      startY: y,
      head: [["Field", "Value"]],
      body: [
        ["Filename", result.filename],
        ["Prediction", result.defect],
        ["Category", result.category],
        ["Severity", result.severity],
        ["Risk", result.risk],
        ["Confidence", `${result.confidence}%`],
        [
          "Original Size",
          `${result.original_width} × ${result.original_height}`,
        ],
        ["Processed Size", result.processed_size],
        ["Channels", result.channels],
      ],
    });

    if (detections.length > 0) {

      y = doc.lastAutoTable.finalY + 10;

      autoTable(doc,{
        startY:y,
        head:[["Class","Confidence"]],
        body:detections.map(d=>[
          d.class,
          `${d.confidence}%`
        ])
      });

      y = doc.lastAutoTable.finalY + 10;

    }
         y = doc.lastAutoTable.finalY + 15;

    doc.setFillColor(30, 41, 59);
    doc.rect(15, y - 6, 180, 10, "F");

    doc.setTextColor(255);
    doc.setFont("helvetica","bold");
    doc.setFontSize(13);

    doc.text("Preprocessing Steps",20,y);

    doc.setTextColor(0);

    y += 10;

    result.preprocessing?.forEach((step) => {
      doc.text(`• ${step}`, 20, y);
      y += 8;
    });

    y += 10;

    // Check if enough space is left on the page
    if (y > 240) {
      doc.addPage();
      y = 20;
    }

    doc.setFontSize(14);
    doc.setFont("helvetica", "bold");
    doc.text("Inspection Summary", 15, y);

    y += 10;

    doc.setFont("helvetica", "normal");
    doc.setFontSize(11);

    doc.text(
      `Prediction : ${result.defect}`,
      15,
      y
    );

    y += 8;

    doc.text(
      `Category : ${result.category}`,
      15,
      y
    );

    y += 8;

    doc.text(
      `Severity : ${result.severity}`,
      15,
      y
    );

    y += 8;

    doc.text(
      `Risk Level : ${result.risk}`,
      15,
      y
    );

    y += 8;

    doc.text(
      `Generated : ${new Date().toLocaleString()}`,
      15,
      y
    );

    // Footer
    y += 15;

    doc.setDrawColor(180);
    doc.line(15, y, 195, y);

    y += 8;

    doc.setFontSize(10);

    doc.text(
      "Generated by VisionInspect AI",
      105,
      y,
      {
        align: "center",
      }
    );

    doc.save("Inspection_Report.pdf");
  };

  if (!result) {
    return (
      <Layout title="Results">
        <h2 className="text-center text-xl mt-10">
          No inspection result found.
        </h2>
      </Layout>
    );
  }

  return (
    <Layout title="AI Inspection">


        <>
                  {/* AI Analysis */}
          <div className="grid lg:grid-cols-2 gap-8 mt-10">

            {/* Prediction Result */}
            <div className="bg-[#1F2937] rounded-2xl p-6 shadow-lg">

              <div className="flex items-center gap-3 mb-6">
                <ShieldCheck className="text-emerald-400" />
                <h2 className="text-2xl font-bold">
                  AI Prediction
                </h2>
              </div>

              <div className="space-y-5">

                <div className="flex justify-between border-b border-gray-700 pb-3">
                  <span className="text-gray-400">
                    Prediction
                  </span>

                  <span
                    className={`font-bold ${
                      result.defect === "Defective"
                        ? "text-red-400"
                        : "text-green-400"
                    }`}
                  >
                    {result.defect}
                  </span>
                </div>

                <div className="flex justify-between border-b border-gray-700 pb-3">
                  <span className="text-gray-400">
                    Confidence
                  </span>

                  <span className="font-bold">
                    {result.confidence}%
                  </span>
                </div>

                <div className="flex justify-between border-b border-gray-700 pb-3">
                  <span className="text-gray-400">
                    Category
                  </span>

                  <span className="font-bold text-blue-400">
                    {result.category}
                  </span>
                </div>

                <div className="flex justify-between border-b border-gray-700 pb-3">
                  <span className="text-gray-400">
                    Severity
                  </span>

                  <span
                    className={`font-bold ${
                      result.severity === "High"
                        ? "text-red-400"
                        : result.severity === "Medium"
                        ? "text-yellow-400"
                        : "text-green-400"
                    }`}
                  >
                    {result.severity}
                  </span>
                </div>

                <div className="flex justify-between">
                  <span className="text-gray-400">
                    Risk Level
                  </span>

                  <span
                    className={`font-bold ${
                      result.risk === "High Risk"
                        ? "text-red-400"
                        : result.risk === "Medium Risk"
                        ? "text-yellow-400"
                        : "text-green-400"
                    }`}
                  >
                    {result.risk}
                  </span>
                </div>

              </div>

            </div>

            {/* Image Information */}
            <div className="bg-[#1F2937] rounded-2xl p-6 shadow-lg">

              <div className="flex items-center gap-3 mb-6">
                <ImageIcon className="text-blue-400" />
                <h2 className="text-2xl font-bold">
                  Image Information
                </h2>
              </div>

              <div className="space-y-5">

                <div className="flex justify-between border-b border-gray-700 pb-3">
                  <span className="text-gray-400">
                    Filename
                  </span>

                  <span>{result.filename}</span>
                </div>

                <div className="flex justify-between border-b border-gray-700 pb-3">
                  <span className="text-gray-400">
                    Original Size
                  </span>

                  <span>
                    {result.original_width} × {result.original_height}
                  </span>
                </div>

                <div className="flex justify-between border-b border-gray-700 pb-3">
                  <span className="text-gray-400">
                    Processed Size
                  </span>

                  <span>{result.processed_size}</span>
                </div>

                <div className="flex justify-between">
                  <span className="text-gray-400">
                    Channels
                  </span>

                  <span>{result.channels}</span>
                </div>

              </div>

            </div>

          </div>
                    {/* Processed Image */}
          <div className="mt-10 bg-[#1F2937] rounded-2xl p-6 shadow-lg">

            <div className="flex items-center gap-3 mb-6">
              <ImageIcon className="text-blue-400" />

              <h2 className="text-2xl font-bold">
                Processed Image
              </h2>
            </div>

            <div className="flex justify-center">

              <img
                src={processedImage}
                    onError={(e) => {
                      e.target.style.display = "none";
                   }}
                alt="Processed"
                className="rounded-xl border border-gray-700 max-h-[450px]"
              />

            </div>

          </div>
          {/* Object Detection Results */}

          <div className="mt-10 bg-[#1F2937] rounded-2xl p-6 shadow-lg">

            <div className="flex items-center gap-3 mb-6">
              <AlertTriangle className="text-red-400" />
              <h2 className="text-2xl font-bold">
                Object Detection Results
              </h2>
            </div>

            {detections.length > 0 ? (

              <div className="overflow-x-auto">

                <table className="w-full">

                  <thead>

                    <tr className="border-b border-gray-700">

                      <th className="py-3 text-left">#</th>
                      <th className="py-3 text-left">Class</th>
                      <th className="py-3 text-left">Confidence</th>
                      <th className="py-3 text-left">Bounding Box</th>

                    </tr>

                  </thead>

                  <tbody>

                    {detections.map((d, index) => (

                      <tr
                        key={index}
                        className="border-b border-gray-800"
                      >

                        <td className="py-3">{index + 1}</td>

                        <td className="py-3 text-blue-400">
                          {d.class}
                        </td>

                        <td className="py-3">
                          {d.confidence}%
                        </td>

                        <td className="py-3 text-gray-300">
                          {d.bbox.join(", ")}
                        </td>

                      </tr>

                    ))}

                  </tbody>

                </table>

              </div>

            ) : (

              <p className="text-green-400">
                No objects detected.
              </p>

            )}

          </div>

          {/* Image Preprocessing */}
          <div className="mt-10 bg-[#1F2937] rounded-2xl p-6 shadow-lg">

            <div className="flex items-center gap-3 mb-6">

              <Layers className="text-emerald-400" />

              <h2 className="text-2xl font-bold">
                Image Preprocessing
              </h2>

            </div>

            <div className="space-y-4">

              {result.preprocessing?.map((step, index) => (

                <div
                  key={index}
                  className="bg-[#111827] rounded-xl p-4 flex items-center gap-3"
                >

                  <CheckCircle className="text-green-400" />

                  <span>{step}</span>

                </div>

              ))}

            </div>

          </div>

          {/* Quality Risk Assessment */}
          <div className="mt-10 bg-[#1F2937] rounded-2xl p-6 shadow-lg">

            <div className="flex items-center gap-3 mb-6">
              <AlertTriangle className="text-red-400" size={24} />

              <h2 className="text-2xl font-bold">
                Quality Risk Assessment
              </h2>
            </div>

            <div
              className={`rounded-xl border p-6 ${
                result.risk === "High Risk"
                  ? "border-red-500/60 bg-red-500/10"
                  : result.risk === "Medium Risk"
                  ? "border-yellow-500/60 bg-yellow-500/10"
                  : "border-green-500/60 bg-green-500/10"
              }`}
            >
              <h3
                className={`text-xl font-bold mb-3 ${
                  result.risk === "High Risk"
                    ? "text-red-400"
                    : result.risk === "Medium Risk"
                    ? "text-yellow-400"
                    : "text-green-400"
                }`}
              >
                {result.risk}
              </h3>

              <p className="text-gray-200 mb-5">
                {result.risk === "High Risk"
                  ? "Critical quality issue detected. Immediate action is recommended."
                  : result.risk === "Medium Risk"
                  ? "Moderate quality issue detected. Inspection and corrective action are recommended."
                  : "Product quality is acceptable. No immediate action is required."}
              </p>

              <h4 className="font-semibold text-white text-lg mb-4">
                Recommendation
              </h4>

              <div className="space-y-4">

                {result.risk === "High Risk" && (
                  <>
                    <div className="flex items-start gap-3">
                      <CheckCircle className="text-green-400 w-5 h-5 mt-1" />
                      <span>Reject the product before shipment.</span>
                    </div>

                    <div className="flex items-start gap-3">
                      <CheckCircle className="text-green-400 w-5 h-5 mt-1" />
                      <span>Perform immediate quality inspection.</span>
                    </div>

                    <div className="flex items-start gap-3">
                      <CheckCircle className="text-green-400 w-5 h-5 mt-1" />
                      <span>Review the manufacturing process.</span>
                    </div>
                  </>
                )}

                {result.risk === "Medium Risk" && (
                  <>
                    <div className="flex items-start gap-3">
                      <CheckCircle className="text-green-400 w-5 h-5 mt-1" />
                      <span>Inspect the affected product carefully.</span>
                    </div>

                    <div className="flex items-start gap-3">
                      <CheckCircle className="text-green-400 w-5 h-5 mt-1" />
                      <span>Schedule maintenance if necessary.</span>
                    </div>

                    <div className="flex items-start gap-3">
                      <CheckCircle className="text-green-400 w-5 h-5 mt-1" />
                      <span>Continue monitoring production quality.</span>
                    </div>
                  </>
                )}

                {result.risk === "Low Risk" && (
                  <>
                    <div className="flex items-start gap-3">
                      <CheckCircle className="text-green-400 w-5 h-5 mt-1" />
                      <span>Approve the product for production.</span>
                    </div>

                    <div className="flex items-start gap-3">
                      <CheckCircle className="text-green-400 w-5 h-5 mt-1" />
                      <span>Maintain regular quality inspections.</span>
                    </div>

                    <div className="flex items-start gap-3">
                      <CheckCircle className="text-green-400 w-5 h-5 mt-1" />
                      <span>Continue preventive maintenance.</span>
                    </div>
                  </>
                )}

              </div>

            </div>

          </div>

          {/* Download Report */}

          <div className="mt-10 flex justify-center">

            <button
              onClick={downloadPDF}
              className="bg-emerald-500 hover:bg-emerald-600 px-8 py-4 rounded-xl font-bold flex items-center gap-3 transition"
            >

              <Download size={22} />

              Download Inspection Report

            </button>

          </div>
                  </>

    </Layout>
  );
}

export default Results;